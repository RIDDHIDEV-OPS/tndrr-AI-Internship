def build_dataset(seed: int = 42) -> list[dict]:
    """Combine all examples into a flat list with input/output pairs."""
    random.seed(seed)
    all_examples = USER_PROFILE_EXAMPLES + PRODUCT_SEARCH_EXAMPLES + BOOKING_EXAMPLES

    dataset = []
    for text, json_obj in all_examples:
        dataset.append({
            "input": text,
            "output": json.dumps(json_obj, separators=(",", ":")),
        })

    random.shuffle(dataset)
    return dataset


def split_dataset(dataset: list[dict], train_count: int = 195, val_count: int = 25):
    """
    Split dataset into train, val, and held-out test splits.
    Guarantees at least 50 examples in the held-out test set (meets assignment requirement).
    With 277 total examples:
      - Train : 195 examples (~70%)
      - Val   : 25 examples (~9%)
      - Test  : 57 examples (~21%, >=50 held-out examples)
    """
    n = len(dataset)
    train_end = min(train_count, n - 60)
    val_end = train_end + val_count
    return dataset[:train_end], dataset[train_end:val_end], dataset[val_end:]


def save_splits(output_dir: str, train, val, test):
    Path(output_dir).mkdir(parents=True, exist_ok=True)
    for name, split in [("train", train), ("val", val), ("test", test)]:
        path = os.path.join(output_dir, f"{name}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(split, f, indent=2)
        print(f"Saved {len(split):3d} examples → {path}")


def main():
    parser = argparse.ArgumentParser(description="Generate English→JSON synthetic dataset")
    parser.add_argument("--output_dir", default="./data", help="Directory to save JSON splits")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    dataset = build_dataset(seed=args.seed)
    train, val, test = split_dataset(dataset)

    print(f"\nDataset stats:")
    print(f"  Total examples : {len(dataset)}")
    print(f"  Train          : {len(train)}")
    print(f"  Val            : {len(val)}")
    print(f"  Test           : {len(test)}")
    print()

    save_splits(args.output_dir, train, val, test)
    print("\nDone! Dataset saved successfully.")


if __name__ == "__main__":
    main()
